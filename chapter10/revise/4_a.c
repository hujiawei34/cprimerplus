#include <stdio.h>
int main(void)
{
    //a.
    int *ptr;//指向int ，步长4 
    int (*pt2)[2];//指向int[2]，步长8 （2*sizeof int)
    int torf[2][2]={12,14,16};//{{12,14},{16,0}}
    ptr=torf[0];//ptr point to {12,14} 中12 的 location，步长4（int 字节）
    printf("*ptr =%d ,*(ptr+2)=%d\n",*ptr,*(ptr+2));//*ptr=12 ,*(ptr+2) 步长+2 int，指向数值为16的数组元素，因为多维数组在内存也是按一维分布的
    pt2=torf;//指向12，步长2*int
    // *pt2 是 int[2] 类型，需要再解引用一次才能得到 int,*(*pt2+1)=torf[1][0]=14
    printf("**pt2=%d, *(*pt2+1)=%d\n", **pt2, *(*pt2+1));
    // pt2+1 指向下一行 **(pt2+1)=torf[1][0] =16,*(*(pt2+1)+1)=tr[1][1]=0
    printf("**(pt2+1)=%d, *(*(pt2+1)+1)=%d\n", **(pt2+1), *(*(pt2+1)+1));
    
/**以下注释说明这两个指针的区别：
 * 内存布局和指针对比

  内存中的 torf[2][2]:
  地址:    [0]  [4]  [8]  [12]  (假设int是4字节)
  值:      12   14   16   0
           └─────┘  └─────┘
           torf[0]  torf[1]

  int *ptr 的行为

  ptr = torf[0];  // ptr 指向地址[0]

  *ptr       → 12   (地址[0])
  *(ptr+1)   → 14   (地址[4])
  *(ptr+2)   → 16   (地址[8])  ← 跨越了行边界！
  *(ptr+3)   → 0    (地址[12])

  ptr+1 移动 4 字节

  int (*pt2)[2] 的行为

  pt2 = torf;     // pt2 指向整个 torf[0] 数组

  *pt2       → int[2] 类型，指向 {12, 14}
  **pt2      → 12   (torf[0][0])
  *(*pt2+1)  → 14   (torf[0][1])

  *(pt2+1)   → int[2] 类型，指向 {16, 0}
  **(pt2+1)  → 16   (torf[1][0])
  *(*(pt2+1)+1) → 0 (torf[1][1])

  pt2+1 移动 8 字节（整行）

  关键区别总结

  | 特性      | int *ptr   | int (*pt2)[2]  |
  |---------|------------|----------------|
  | 指向      | 单个 int     | 包含2个int的数组     |
  | 步长      | 4字节（1个int） | 8字节（2个int）     |
  | 解引用1次   | 得到 int     | 得到 int* (数组退化) |
  | 解引用2次   | 非法         | 得到 int         |
  | 是否保持行边界 | ❌ 不保持      | ✅ 保持           |

  使用场景

  - int *ptr: 当你想把二维数组当作一维数组处理时
  - int (*pt2)[2]: 当你想保持二维数组的行结构时（更安全）
 */
    return 0;
}